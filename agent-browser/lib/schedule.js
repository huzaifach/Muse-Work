// SCHEDULER: run agent-browser bulk jobs on a cron schedule.
// Design (simple + robust, no system cron required):
//   schedule add --cron "0 9 * * *" --name morning -- bulk --input urls.jsonl --actions actions.json
//     → writes a job definition to ~/.agent-browser/schedule/jobs.json and a
//       self-contained run.sh that executes bulk with TIMESTAMPED outputs.
//   schedule daemon [--foreground]
//     → lightweight node loop (checks every 30s) that executes due jobs.
//       Run it under your platform's process supervision, or nohup.
//   schedule list | schedule remove --name x | schedule run-now <name>
// Cron expression: standard 5-field (min hour dom month dow). Supports
// *, ranges, lists, steps. dom+dow both restricted => OR (standard cron).
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawn, execSync } = require('child_process');
const { ensureDir } = require('./util');

const SCHED_DIR = path.join(os.homedir(), '.agent-browser', 'schedule');
const JOBS_FILE = path.join(SCHED_DIR, 'jobs.json');

function loadJobs() {
  try { return JSON.parse(fs.readFileSync(JOBS_FILE, 'utf8')); }
  catch { return {}; }
}
function saveJobs(j) {
  ensureDir(SCHED_DIR);
  fs.writeFileSync(JOBS_FILE, JSON.stringify(j, null, 1));
}
function jobDir(name) { return path.join(SCHED_DIR, name); }

// ---- minimal cron matcher ----

function parseField(field, min, max) {
  const vals = new Set();
  const num = (s, fb) => {
    const n = parseInt(s, 10);
    return Number.isNaN(n) ? fb : Math.min(Math.max(n, min), max);
  };
  for (const part of String(field).split(',')) {
    let range = part, step = 1;
    const slash = part.indexOf('/');
    if (slash > 0) { range = part.slice(0, slash); step = Math.max(1, num(part.slice(slash + 1), 1)); }
    let lo = min, hi = max;
    if (range === '' || range === '*') { /* full range */ }
    else if (range.includes('-')) { const [a, b] = range.split('-'); lo = num(a, min); hi = num(b, max); }
    else lo = hi = num(range, min);
    for (let v = lo; v <= hi; v += step) vals.add(v);
  }
  return vals;
}

function cronDue(expr, date) {
  const parts = String(expr).trim().split(/\s+/);
  if (parts.length !== 5) throw { code: 'BAD_CRON', message: `cron expression needs 5 fields, got ${parts.length}: '${expr}'`, hint: 'e.g. "0 9 * * *" = daily 09:00' };
  const d = date || new Date();
  const mi = parseField(parts[0], 0, 59);
  const hr = parseField(parts[1], 0, 23);
  const dom = parseField(parts[2], 1, 31);
  const mon = parseField(parts[3], 1, 12);
  let dow = parseField(parts[4], 0, 7);
  if (dow.has(7)) { dow.add(0); dow.delete(7); }
  if (!mi.has(d.getMinutes()) || !hr.has(d.getHours()) || !mon.has(d.getMonth() + 1)) return false;
  const domStar = parts[2] === '*';
  const dowStar = parts[3 + 1] === '*';
  const domOk = dom.has(d.getDate());
  const dowOk = dow.has(d.getDay());
  if (!domStar && !dowStar) return domOk || dowOk; // standard cron: OR
  return domOk && dowOk;
}

// ---- job management ----

function addJob({ name, cron, bulkArgs, cwd, binPath }) {
  if (!name || !/^[a-zA-Z0-9][a-zA-Z0-9_-]*$/.test(name)) {
    throw { code: 'BAD_NAME', message: `bad job name '${name}'`, hint: 'use letters, numbers, dash, underscore' };
  }
  cronDue(cron, new Date()); // validates the expression (throws BAD_CRON)
  if (!bulkArgs.length || bulkArgs[0] !== 'bulk') {
    throw { code: 'BAD_ARGS', message: 'schedule add runs bulk jobs: put `bulk ...` after `--`', hint: 'schedule add --cron "0 9 * * *" --name x -- bulk --input urls.jsonl --actions actions.json' };
  }
  const jobs = loadJobs();
  if (jobs[name]) throw { code: 'DUP_JOB', message: `job '${name}' already exists`, hint: `schedule remove --name ${name} first` };
  const dir = jobDir(name);
  ensureDir(path.join(dir, 'runs'));
  const runSh = path.join(dir, 'run.sh');
  const quoted = bulkArgs.map((a) => `'${String(a).replace(/'/g, `'\\''`)}'`).join(' ');
  fs.writeFileSync(runSh,
    `#!/bin/bash\n# agent-browser scheduled job: ${name}\n# generated by 'schedule add' — edit via schedule remove/add, not by hand\nset -u\nTS=$(date +%Y%m%d-%H%M%S)\nOUTDIR="${dir}/runs/$TS"\nmkdir -p "$OUTDIR"\ncd ${JSON.stringify(cwd)}\n"${process.execPath}" ${JSON.stringify(binPath)} ${quoted} --out "$OUTDIR/results.jsonl" >> "$OUTDIR/run.log" 2>&1\necho "exit=$? ts=$TS" >> "$OUTDIR/run.log"\n`);
  fs.chmodSync(runSh, 0o755);
  jobs[name] = { name, cron, bulkArgs, cwd, binPath, created: new Date().toISOString(), runs: 0, lastRun: null, lastStatus: null };
  saveJobs(jobs);
  return { name, cron, runSh, summary: `scheduled '${name}' (${cron}) → ${runSh}` };
}

function removeJob(name) {
  const jobs = loadJobs();
  if (!jobs[name]) throw { code: 'NO_JOB', message: `no job named '${name}'`, hint: 'schedule list to see jobs' };
  delete jobs[name];
  saveJobs(jobs);
  return { removed: name, keptDir: jobDir(name), summary: `removed job '${name}' (past run outputs kept at ${jobDir(name)}/runs)` };
}

function listJobs() {
  return Object.values(loadJobs()).map((j) => ({
    name: j.name, cron: j.cron, runs: j.runs, lastRun: j.lastRun, lastStatus: j.lastStatus,
  }));
}

function runJobNow(name) {
  const jobs = loadJobs();
  const j = jobs[name];
  if (!j) throw { code: 'NO_JOB', message: `no job named '${name}'` };
  const out = execSync(`bash ${JSON.stringify(path.join(jobDir(name), 'run.sh'))} 2>&1`, { encoding: 'utf8', timeout: 30 * 60 * 1000 });
  jobs[name].runs = (jobs[name].runs || 0) + 1;
  jobs[name].lastRun = new Date().toISOString();
  saveJobs(jobs);
  return { name, summary: `ran job '${name}' now (see ${jobDir(name)}/runs for outputs)`, logTail: out.slice(-500) };
}

// Foreground loop: every 30s, run jobs whose cron matches the current minute
// (tracked per job so a minute never double-fires).
async function daemonLoop({ foreground = false } = {}) {
  if (!foreground) {
    const child = spawn(process.execPath, [process.argv[1], 'schedule', 'daemon', '--foreground'], {
      detached: true, stdio: 'ignore', cwd: process.cwd(),
    });
    child.unref();
    return { daemonized: true, pid: child.pid, summary: `schedule daemon started (pid ${child.pid}); jobs in ${SCHED_DIR}` };
  }
  console.error(`agent-browser schedule daemon running; jobs dir: ${SCHED_DIR}`);
  const firedMinute = {};
  for (;;) {
    const now = new Date();
    const minuteKey = `${now.getFullYear()}-${now.getMonth()}-${now.getDate()} ${now.getHours()}:${now.getMinutes()}`;
    const jobs = loadJobs();
    for (const j of Object.values(jobs)) {
      const key = `${j.name}@${minuteKey}`;
      if (firedMinute[key]) continue;
      let due = false;
      try { due = cronDue(j.cron, now); } catch (e) { console.error(`bad cron for job '${j.name}': ${e.message}`); }
      if (due) {
        firedMinute[key] = true;
        console.error(`[${now.toISOString()}] running scheduled job '${j.name}'`);
        try {
          execSync(`bash ${JSON.stringify(path.join(jobDir(j.name), 'run.sh'))}`, { timeout: 6 * 3600 * 1000 });
          j.lastStatus = 'ok';
        } catch (e) { j.lastStatus = 'failed'; console.error(`job '${j.name}' failed: ${e.message}`); }
        j.runs = (j.runs || 0) + 1;
        j.lastRun = now.toISOString();
        const all = loadJobs(); all[j.name] = j; saveJobs(all);
      }
    }
    await new Promise((r) => setTimeout(r, 30000));
  }
}

module.exports = { addJob, removeJob, listJobs, runJobNow, daemonLoop, cronDue, SCHED_DIR };
